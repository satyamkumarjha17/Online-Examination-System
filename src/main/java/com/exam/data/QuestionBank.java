    public static List<Question> getQuestions(String subject) {
        List<Question> list = new ArrayList<>();
        switch (subject) {
            case "Java" -> javaQuestions(list);
            case "Aptitude" -> aptitudeQuestions(list);
            case "General Knowledge" -> gkQuestions(list);
        }
        return list;
    }

    private static void q(List<Question> l, String s, String text, int correct, String... opts) {
        l.add(new Question(s, text, List.of(opts), correct));
    }

